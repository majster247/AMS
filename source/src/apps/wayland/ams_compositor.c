/**
 * @file ams_compositor.c
 * @brief AMS-OS Wayland compositor using wlroots, DRM/KMS, GBM, libinput,
 *        pixman/cairo, and wayland-scanner-generated protocol bindings.
 *
 * Architecture:
 *  - wlroots provides the Wayland server infrastructure (wl_display, seats,
 *    outputs, renderer) through its wlr_* API.
 *  - The DRM backend (wlr_backend_autocreate with AMS drm fd) drives the KMS
 *    CRTC via GEM dumb buffers and page flips.
 *  - GBM (Mesa) is used as the buffer allocator for hardware-accelerated
 *    surfaces; software fallback uses SHM pools (POSIX shm_open + mmap).
 *  - libinput handles pointer and keyboard events, forwarded through the
 *    wlroots seat abstraction.
 *  - pixman handles CPU-side surface composition for SHM clients.
 *  - cairo is used for desktop chrome (title bars, status bar).
 *  - wayland-scanner-generated xdg-shell, xdg-output, and
 *    wlr-layer-shell protocols are supported.
 *
 * Build-time dependencies (resolved by the wlroots/mesa/libinput port scripts):
 *   - libwlroots.a / libwlroots.so
 *   - libgbm.so  (Mesa)
 *   - libEGL.so  (Mesa)
 *   - libGL.so   (Mesa swrast or llvmpipe)
 *   - libinput.so
 *   - libpixman-1.so
 *   - libcairo.so
 *   - libwayland-server.so
 *   - xdg-shell-protocol.c  (generated by wayland-scanner)
 *   - wlr-layer-shell-unstable-v1-protocol.c
 */

