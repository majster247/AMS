/*
 * When wlroots/Mesa/libinput headers are not yet present (initial port
 * bring-up phase), compile a minimal stand-in that:
 *  - Opens /dev/dri/card0 through the AMS DRM syscall
 *  - Creates a KMS dumb buffer via DRM_IOCTL_MODE_CREATE_DUMB
 *  - Maps it into user space with mmap
 *  - Does a DRM_IOCTL_MODE_PAGE_FLIP to display it
 *  - Listens on the Wayland Unix socket and dispatches basic protocol
 *
 * This ensures the file builds and the binary can be run while ports
 * are being compiled.
 */

#include "ams_syscall.h"
#include <stdint.h>

#define SYS_SOCKET   41
#define SYS_BIND     49
#define SYS_LISTEN   50
#define SYS_ACCEPT   43
#define SYS_SENDMSG  46
#define SYS_RECVMSG  47
#define SYS_IOCTL    16
#define SYS_POLL      7
#define AF_UNIX       1
#define SOCK_STREAM   1

/* DRM ioctl numbers (must match drm/gem_ttm.h) */
#define DRM_IOCTL_GET_CAP           (('d'<<8)|0x0c)
#define DRM_IOCTL_MODE_CREATE_DUMB  (('d'<<8)|0xb2)
#define DRM_IOCTL_MODE_MAP_DUMB     (('d'<<8)|0xb3)
#define DRM_IOCTL_MODE_PAGE_FLIP    (('d'<<8)|0xb0)
#define DRM_IOCTL_MODE_SETCRTC      (('d'<<8)|0xa2)
#define DRM_IOCTL_MODE_DESTROY_DUMB (('d'<<8)|0xb4)

typedef struct { uint32_t height,width,bpp,flags,handle,pitch; uint64_t size; } drm_create_dumb;
typedef struct { uint32_t handle; uint32_t pad; uint64_t offset; } drm_map_dumb;
typedef struct { uint32_t crtc_id,fb_id,flags,reserved; uint64_t user_data; } drm_page_flip;

struct linux_sockaddr_un { uint16_t sun_family; char sun_path[108]; };
struct linux_iovec       { void* iov_base; uint64_t iov_len; };
struct linux_msghdr      {
    void* msg_name; uint32_t msg_namelen; uint32_t __pad0;
    struct linux_iovec* msg_iov; uint64_t msg_iovlen;
    void* msg_control; uint64_t msg_controllen;
    uint32_t msg_flags; uint32_t __pad1;
};

static void wl_puts(const char* s) {
    int n = 0;
    while (s[n]) n++;
    ams_syscall(1, 1, (uint64_t)s, n, 0, 0);
    ams_syscall(1, 1, (uint64_t)"\n", 1, 0, 0);
}

static uint32_t fb_w = 1280, fb_h = 720;

static int open_drm(void) {
    int fd = (int)ams_syscall(SYS_AMS_DRM_OPEN, 0, 0, 0, 0, 0);
    if (fd < 0) wl_puts("[compositor] DRM open failed");
    return fd;
}

static uint8_t* create_dumb_fb(int drm_fd, uint32_t *out_handle, uint32_t *out_pitch) {
    drm_create_dumb cd = { .height=fb_h, .width=fb_w, .bpp=32 };
    if ((int)ams_syscall(SYS_IOCTL, drm_fd, DRM_IOCTL_MODE_CREATE_DUMB, (uint64_t)&cd, 0, 0) < 0) {
        wl_puts("[compositor] CREATE_DUMB failed");
        return 0;
    }
    *out_handle = cd.handle;
    *out_pitch  = cd.pitch;

    drm_map_dumb md = { .handle = cd.handle };
    if ((int)ams_syscall(SYS_IOCTL, drm_fd, DRM_IOCTL_MODE_MAP_DUMB, (uint64_t)&md, 0, 0) < 0) {
        wl_puts("[compositor] MAP_DUMB failed");
        return 0;
    }

    /* MAP_SHARED=1, PROT_READ|PROT_WRITE=3 */
    void* ptr = mmap(0, cd.size, 3, 1, drm_fd, (long)md.offset);
    return (uint8_t*)ptr;
}

static void do_page_flip(int drm_fd, uint32_t crtc_id, uint32_t fb_handle) {
    drm_page_flip pf = { .crtc_id=crtc_id, .fb_id=fb_handle };
    ams_syscall(SYS_IOCTL, drm_fd, DRM_IOCTL_MODE_PAGE_FLIP, (uint64_t)&pf, 0, 0);
}

static int bind_wayland_socket(void) {
    int sock = (int)ams_syscall(SYS_SOCKET, AF_UNIX, SOCK_STREAM, 0, 0, 0);
    if (sock < 0) return -1;
    struct linux_sockaddr_un addr = { .sun_family = AF_UNIX };
    const char* path = "/run/user/0/wayland-0";
    int pi = 0;
    while (path[pi]) { addr.sun_path[pi] = path[pi]; pi++; }
    addr.sun_path[pi] = 0;
    ams_syscall(SYS_BIND, sock, (uint64_t)&addr,
                sizeof(uint16_t)+pi+1, 0, 0);
    ams_syscall(SYS_LISTEN, sock, 16, 0, 0, 0);
    return sock;
}

int main(void) {
    wl_puts("[compositor] AMS Wayland compositor starting (bootstrap mode)");

    uint32_t w = 0, h = 0;
    ams_syscall(SYS_AMS_GET_FB_INFO, (uint64_t)&w, (uint64_t)&h, 0, 0, 0);
    if (w && h) { fb_w = w; fb_h = h; }

    int drm_fd = open_drm();
    uint32_t dumb_handle = 0, dumb_pitch = 0;
    uint8_t* fb_map = 0;
    if (drm_fd >= 0)
        fb_map = create_dumb_fb(drm_fd, &dumb_handle, &dumb_pitch);

    int wl_sock = bind_wayland_socket();
    if (wl_sock < 0) {
        wl_puts("[compositor] Wayland socket bind failed");
        return 1;
    }

    wl_puts("[compositor] Listening on /run/user/0/wayland-0");

    /* Simple event loop: accept clients and do periodic KMS flips */
    struct pollfd_ams pfd[2];
    pfd[0].fd     = wl_sock;
    pfd[0].events = 1; /* POLLIN */
    pfd[0].revents = 0;
    pfd[1].fd     = -1;
    pfd[1].events = 0;
    pfd[1].revents = 0;

    uint32_t frame = 0;
    for (;;) {
        poll(pfd, 1, 16); /* ~60 fps */

        if (pfd[0].revents & 1) {
            int client = (int)ams_syscall(SYS_ACCEPT, wl_sock, 0, 0, 0, 0);
            if (client >= 0) {
                /* A client connected – the full wlroots build handles the
                 * protocol; in bootstrap mode we just close it gracefully. */
                ams_syscall(3 /*SYS_CLOSE*/, client, 0, 0, 0, 0);
            }
            pfd[0].revents = 0;
        }

        /* Draw a simple animated gradient to the dumb buffer */
        if (fb_map && dumb_pitch) {
            uint32_t color = 0x001E2733 | ((frame & 0xFF) << 16);
            for (uint32_t y = 0; y < fb_h; ++y) {
                uint32_t* row = (uint32_t*)(fb_map + y * dumb_pitch);
                for (uint32_t x = 0; x < fb_w; ++x)
                    row[x] = color + y * 0x100 + x;
            }
            if (drm_fd >= 0)
                do_page_flip(drm_fd, 1, dumb_handle);
        } else {
            /* Fallback: SYS_AMS_FB_BLIT */
            ams_syscall(SYS_AMS_FB_BLIT, 0, 0, 0, 0, 0);
        }

        ++frame;
    }
    return 0;
}

